ART_RE = re.compile(r"^\s*제\s*(\d+)\s*조\s*\(((?:[^()]|\([^()]*\))*)\)\s*(.*)$")
CH_RE = re.compile(r"^\s*제\s*(\d+)\s*장\s*(.*)$")
PAGE_RE = re.compile(r"^\s*\d{1,3}\s*$")

def parse(lines, chapter=0):
    """줄 목록 -> [(chapter, art_no, title, text)]"""
    out, cur = [], None
    for raw in lines:
        s = raw.rstrip()
        if not s.strip() or PAGE_RE.match(s):
            continue
        m = CH_RE.match(s)
        if m and not ART_RE.match(s):
            chapter = int(m.group(1))
            continue
        m = ART_RE.match(s)
        if m:
            if cur: out.append(cur)
            cur = [chapter, int(m.group(1)), m.group(2).strip(), [m.group(3).strip()]]
            continue
        if cur is not None:
            t = s.strip()
            if t in ("부 칙", "부칙", "부        칙"):
                continue
            cur[3].append(t)
    if cur: out.append(cur)
    res = []
    for ch, no, title, parts in out:
        text = " ".join(p for p in parts if p)
        text = re.sub(r"\s+", " ", text).strip()
        res.append((ch, no, title, text))
    return res

