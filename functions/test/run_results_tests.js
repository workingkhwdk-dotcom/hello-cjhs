/**
 * 교육활동 결과물 책자(RS01~RS21) 검색·안전성 하네스. 실행: node test/run_results_tests.js
 * 1) 대표 질문 → 기대 문서가 top3(또는 지정 범위)에 오는지
 * 2) 개인정보(학생·강사 실명)와 충돌 수치(학생수·교원수·전화·지정기간)가 RS 문서에 없는지
 * 3) 모든 RS 문서가 2025학년도 실적임을 밝히는지
 */
const { retrieveKnowledge, KNOWLEDGE } = require("../knowledge.js");
let pass = 0, fail = 0; const fails = [];
const check = (n, ok, d) => { ok ? pass++ : (fail++, fails.push(d ? `${n}\n    ${d}` : n)); };
const CASES = [
  ["학교 비전이 뭐예요", ["RS01", "BR01"]], ["학교상 교사상 학생상", ["RS01"]],
  ["교육방침이 뭐예요", ["RS01", "BR01"]],
  ["과제 2 학교특색활동이 뭐예요", ["RS02", "BR02"]],
  ["192학점 고교학점제 어떻게 운영해요", ["RS03"]], ["교육과정 이수 지도팀이 뭐예요", ["RS03"]],
  ["경남참공동교육과정 참여 과목", ["RS03"]],
  ["교사 전문적학습공동체 있나요", ["RS04"]],
  ["3학년 탐구 주제 뭐 했어요", ["RS05"]], ["아두이노 탄소 포집 탐구", ["RS05"]],
  ["1학년 탐구 주제 미세플라스틱", ["RS06"]], ["주제탐구발표대회 언제 해요", ["RS06"]],
  ["커맨드 동아리는 뭐 하나요", ["RS07", "RS19"]], ["테크니션즈 드론 레고", ["RS07"]],
  ["해커톤 한마당이 뭐예요", ["RS08"]], ["비버챌린지 몇 문항", ["RS08"]], ["프로그래밍 한마당 참가", ["RS08"]],
  ["도서관 초대 쿠폰제", ["RS09"]], ["한 학기 한 권 읽기 해요?", ["RS09"]],
  ["수학의 날 마시멜로 타워", ["RS10"]], ["영어의 날 영어 스크래블", ["RS11"]], ["과학의 날 스틱밤 도미노", ["RS12"]],
  ["용비제 언제 해요", ["RS13"]], ["명산 생태 트래킹 어디 가요", ["RS13"]], ["체육대회 날짜", ["RS13"]],
  ["교육감배 탁구 몇 등", ["RS14"]], ["전국카누선수권대회 성적", ["RS14", "BR11"]],
  ["진로심리검사 해석 강의", ["RS15"]], ["경상국립대 모빌리티 진로캠프", ["RS15"]], ["서울대 교수 강연 희소금속", ["RS15"]],
  ["미래교육원 의령 체험", ["RS16"]], ["망개떡 도자공예 체험", ["RS16"]],
  ["전문직업인 특강 어떤 직업", ["RS17"]], ["포스텍 유니스트 과학기행", ["RS17", "BR13"]],
  ["누리교실이 뭐예요", ["RS18", "RS02", "BR02", "BR12"]],
  ["동아리 종류 알려주세요", ["RS19", "RS20"]], ["라따뚜이 동아리 뭐 해요", ["RS19"]], ["수학 독서 동아리 있나요", ["RS20"]], ["밴드 동아리 있어요", ["RS20"]],
  ["온라인 수업교실 배움ON", ["RS21", "BR14"]], ["스쿨존 방지턱 설치", ["RS21"]],
];
for (const [q, ids] of CASES) {
  const got = retrieveKnowledge(q, "", 6).map((r) => r.id);
  check(`[top3] "${q}"`, got.slice(0, 3).some((i) => ids.includes(i)), `기대 ${ids.join("/")} 실제 ${got.join(", ") || "(없음)"}`);
}
const rs = KNOWLEDGE.filter((r) => /^RS\d+$/.test(r.id));
check("[등록] RS01~RS21 21건", rs.length === 21, `실제 ${rs.length}`);
const BAD = [/550\s*명/, /교원\s*52/, /055\)?\s*-?\s*239-?3100/, /2023\s*[~-]\s*2028/, /김민준|정재훈|김막심|박중혁|이준서|이준석|이현기|김장미|백운효|배규한|오성우|박지영|김지윤|김영민|문혜성|김동현|최재령|이정열|장평문|김선미|임○○|정○○/];
for (const r of rs) {
  const hit = BAD.find((re) => re.test(r.retrieval_text));
  check(`[개인정보·충돌 수치 배제] ${r.id}`, !hit, hit ? String(hit) : "");
  check(`[2025 실적 명시] ${r.id}`, /2025학년도 (실적|운영 실적)|2025/.test(r.retrieval_text));
}
{
  const ids = retrieveKnowledge("교무실 전화번호 알려주세요", "", 6).map((r) => r.id);
  check("[연락처] 결과물 문서가 연락처 질문 1등을 가로채지 않음", ids[0] && !/^(RS|BR|CUR)/.test(ids[0]), ids.join(", "));
}
console.log(`\n총 ${pass + fail}건 중 ${pass}건 통과, ${fail}건 실패`);
if (fail) { console.log(fails.map((f) => "- " + f).join("\n")); process.exit(1); }
